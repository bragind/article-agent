import re
import html


def clean_html(text: str) -> str:
    """
    Очистка текста с сохранением кириллицы и основных знаков пунктуации
    
    :param text: Исходный текст
    :return: Очищенный текст
    """
    if not text:
        return ''
    
    # 1. Декодируем HTML-сущности (&amp; -> &, &nbsp; -> пробел и т.д.)
    text = html.unescape(text)
    
    # 2. Заменяем неразрывные пробелы и другие специальные пробелы на обычные
    text = re.sub(r'[\xa0\u2000-\u200f\u2028-\u202f]', ' ', text)
    
    # 3. Удаляем HTML-теги (если остались)
    text = re.sub(r'<[^>]+>', ' ', text)
    
    # 4. Сохраняем: буквы (включая кириллицу), цифры, основные знаки пунктуации, пробелы
    #    Кириллица: \u0400-\u04FF
    #    Знаки пунктуации: . , ! ? : ; ( ) - — « » " ' `
    text = re.sub(r'[^\w\s.,!?:;()\-—«»"\'`\u0400-\u04FF]', ' ', text, flags=re.UNICODE)
    
    # 5. Убираем лишние пробелы и переносы строк
    text = re.sub(r'\s+', ' ', text)
    
    # 6. Обрезаем пробелы в начале и конце
    text = text.strip()
    
    return text